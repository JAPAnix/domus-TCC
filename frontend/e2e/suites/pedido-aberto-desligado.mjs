import { call, register, publishListing } from '../lib/fixtures.mjs';
let pass = 0, fail = 0;
const ok = (name, cond, extra = '') => { cond ? pass++ : fail++; console.log((cond ? 'ok  ' : 'FAIL') + ' ' + name + (cond ? '' : ' ' + JSON.stringify(extra).slice(0, 300))); };
const cli = await register('FlagCli'), pro = await register('FlagPro');
await publishListing(pro);
const l = await call('POST', '/auth/login', { email: pro.email, password: 'senha-forte-1' }); pro.token = l.d.token;
const f = await call('GET', '/features');
ok('GET /features diz que o pedido aberto está desligado', f.d.openRequests === false, f);
const cats = (await call('GET', '/categories')).d;
ok('publicar pedido: 404', (await call('POST', '/services', { title: 'Pintar sala', description: 'Descrição longa o bastante para validar.', category_id: cats[0].id, city: 'Curitiba', state: 'PR' }, cli.token)).s === 404);
ok('lista pública de pedidos abertos: 404', (await call('GET', '/services')).s === 404);
ok('rascunho: 404', (await call('GET', '/services/draft', null, cli.token)).s === 404);
ok('oportunidades: 404', (await call('GET', '/pro/opportunities', null, pro.token)).s === 404);
ok('os meus pedidos antigos continuam acessíveis', (await call('GET', '/services/mine', null, cli.token)).s === 200);
ok('pedidos por anúncio continuam funcionando', (await call('GET', '/orders/badges', null, pro.token)).s === 200);
const b = await call('GET', '/orders/badges', null, pro.token);
ok('o selo de oportunidades fica em zero', b.d.opportunities === 0, b.d);
console.log(JSON.stringify({ pass, fail }));
process.exitCode = fail ? 1 : 0;
